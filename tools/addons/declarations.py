"""
The root module's declarations of the add-on modules, a segment generated from addons/.

The root's MODULE.bazel includes addons.MODULE.bazel, which declares each add-on module of
addons/ with an override to its directory, so the root's examples and end-to-end tests
consume the modules as applications do. addons.bzl lists their repositories for the root's
BUILD files, such as the setup checks' data (tools/setup/module_files.bzl), and root.targets
the root's target patterns, its own and the modules', which the development verbs pass to
Bazel as `--target_pattern_file` (.aspect/develop.axl). `aspect generate` writes all three,
the generator writes them for a new module, and the self-test writes them with its own module
for its run.

No Bazel target checks the segment: it bootstraps the root's module graph, which a stale
segment breaks before any test runs, and the root ignores addons/, so no label lists the
modules a check would compare it with. The segment therefore declares only what Bazel
verifies itself: each module's name, which must match its MODULE.bazel, and its directory.
It leaves the version to the override, so a release does not change it, and a module of
addons/ missing from it fails the examples that load it.

Sections: Segment, Repositories, Root targets, Writing.
"""

from collections.abc import Iterable
from pathlib import Path

from tools.addons.modules import module_attributes
from tools.setup.modules import ADDONS, addon_modules

# ==== Segment =================================================================

# The segment, relative to the repository root, and its label in the root's MODULE.bazel.
SEGMENT = Path("addons.MODULE.bazel")


def declaration(name: str, path: str) -> str:
    """The declaration of one add-on module."""
    return (
        f'bazel_dep(name = "{name}", dev_dependency = True)\n'
        "local_path_override(\n"
        f'    module_name = "{name}",\n'
        f'    path = "{path}",\n'
        ")\n"
    )


HEADER = """\
# Generated by tools/addons/declarations.py (`aspect generate`) from the modules of addons/;
# do not edit. The root module's examples and end-to-end tests consume each add-on module
# from its directory.
"""


def segment(found: list[tuple[str, str]]) -> str:
    """The segment that declares the modules, each by name and directory."""
    return HEADER + "".join(f"\n{declaration(*module)}" for module in found)


# ==== Repositories ============================================================

# The add-on modules' repositories, by apparent name, for the root's BUILD files.
REPOSITORIES = Path("addons.bzl")

REPOSITORIES_HEADER = '''"""
Generated by tools/addons/declarations.py (`aspect generate`) with addons.MODULE.bazel; do not
edit. The add-on modules the root module declares, by their repositories' apparent names.
"""
'''


def repositories(found: list[tuple[str, str]]) -> str:
    """The .bzl file that lists the repositories of the modules."""
    names = "".join(f'    "@{name}",\n' for name, _ in found)
    return f"{REPOSITORIES_HEADER}\nADDON_REPOSITORIES = [\n{names}]\n"


# ==== Root targets ============================================================

# The root module's target patterns, its own and the add-on modules', one per line.
TARGETS = Path("root.targets")

TARGETS_HEADER = """\
# Generated by tools/addons/declarations.py (`aspect generate`) with addons.MODULE.bazel; do
# not edit. The root module's target patterns, the add-on modules' included, for Bazel's
# --target_pattern_file.
"""


def targets(found: list[tuple[str, str]]) -> str:
    """The target pattern file of the root module and the modules."""
    patterns = ["//...", *(f"@{name}//..." for name, _ in found)]
    return TARGETS_HEADER + "".join(f"{pattern}\n" for pattern in patterns)


# ==== Writing =================================================================


def modules(root: Path, extra: Iterable[str] = ()) -> list[tuple[str, str]]:
    """
    The name and directory of each add-on module of the checkout and the extra directories,
    by its MODULE.bazel's name.
    """
    directories = sorted({*(Path(module).name for module in addon_modules(root)), *extra})
    paths = [f"{ADDONS}/{directory}" for directory in directories]
    return [
        (str(module_attributes((root / path / "MODULE.bazel").read_text())["name"]), path)
        for path in paths
    ]


def write(root: Path, extra: Iterable[str] = ()) -> list[Path]:
    """
    Write the segment, its repositories and the root's target patterns, with the extra
    directories' modules too.
    """
    found = modules(root, extra)
    files = {
        SEGMENT: segment(found),
        REPOSITORIES: repositories(found),
        TARGETS: targets(found),
    }
    for path, text in files.items():
        (root / path).write_text(text)
    return [root / path for path in files]
