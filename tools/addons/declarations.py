"""
The root module's declarations of the add-on modules, a segment generated from addons/.

The root's MODULE.bazel includes addons.MODULE.bazel, which declares each add-on module of
addons/ with an override to its directory, so the root's examples and end-to-end tests
consume the modules as applications do. `aspect generate` writes it, the generator writes it
for a new module, and the self-test writes it with its own module for its run.
"""

from collections.abc import Iterable
from pathlib import Path

from tools.addons.modules import module_attributes
from tools.setup.modules import ADDONS, addon_modules

# The segment, relative to the repository root, and its label in the root's MODULE.bazel.
SEGMENT = Path("addons.MODULE.bazel")
HEADER = """\
# Generated by tools/addons/declarations.py (`aspect generate`) from the modules of addons/;
# do not edit. The root module's examples and end-to-end tests consume each add-on module
# from its directory.
"""


def declaration(root: Path, directory: str) -> str:
    """The declaration of the add-on module addons/<directory>, from its MODULE.bazel."""
    path = f"{ADDONS}/{directory}"
    attributes = module_attributes((root / path / "MODULE.bazel").read_text())
    name = attributes["name"]
    return (
        f'bazel_dep(name = "{name}", version = "{attributes.get("version", "")}",'
        " dev_dependency = True)\n"
        "local_path_override(\n"
        f'    module_name = "{name}",\n'
        f'    path = "{path}",\n'
        ")\n"
    )


def segment(root: Path, extra: Iterable[str] = ()) -> str:
    """The segment for the add-on modules of the checkout and the extra directories."""
    directories = sorted({*(Path(module).name for module in addon_modules(root)), *extra})
    return HEADER + "".join(f"\n{declaration(root, d)}" for d in directories)


def write(root: Path, extra: Iterable[str] = ()) -> Path:
    """Write the segment, with the extra directories' modules too."""
    path = root / SEGMENT
    path.write_text(segment(root, extra))
    return path


def is_current(root: Path) -> bool:
    """Whether the checked-in segment declares exactly the add-on modules of the checkout."""
    path = root / SEGMENT
    return path.is_file() and path.read_text() == segment(root)
