"""
Write the one file that follows from the add-on modules, or check that it is current.

`addons/consumers.pkl` names the modules of the checkout that use each add-on module, from
their `local_path_override`s; hk.pkl reads it to select their tasks.

`python3 -m tools.addons.generated` (`mise run addons:generate`) writes it;
`--check` (`mise run test:setup`) fails when it is stale. Everything else about a module,
such as its registry templates in `.bcr/addons/<module>/`, is written once by the generator
(tools/addons/new.py) and checked by the conventions (RG015).
"""

import argparse
import json
import sys
from pathlib import Path

from tools.addons.modules import ROOT, consumers

PATH = "addons/consumers.pkl"
CONSUMERS_HEADER = """\
// Generated by `mise run addons:generate` (tools/addons/generated.py) from the MODULE.bazel
// files: the modules of this checkout that use an add-on module through local_path_override,
// by the add-on module's directory. hk.pkl selects their tasks for changes to it.
"""


def consumers_pkl(users: dict[str, tuple[str, ...]]) -> str:
    entries = "".join(
        f"  [{json.dumps(name)}] = List({', '.join(map(json.dumps, modules))})\n"
        for name, modules in users.items()
    )
    return (
        CONSUMERS_HEADER
        + "consumers = new Mapping<String, List<String>> {\n"
        + entries
        + "}\n"
    )


def stale(root: Path = ROOT) -> bool:
    """Whether the file differs from what the modules' overrides say."""
    target = root / PATH
    expected = consumers_pkl(consumers(root))
    return not target.is_file() or target.read_text() != expected


def write(root: Path = ROOT) -> None:
    (root / PATH).parent.mkdir(parents=True, exist_ok=True)
    (root / PATH).write_text(consumers_pkl(consumers(root)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail when the file is stale"
    )
    args = parser.parse_args()
    if not args.check:
        write()
    elif stale():
        sys.exit(f"{PATH} is stale; run `mise run addons:generate`")


if __name__ == "__main__":
    main()
