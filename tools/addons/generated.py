"""
Write the files that follow from the add-on modules, or check that they are current.

- `.bcr/addons/<directory>/`: each module's templates for Publish to BCR: metadata and source
  from its name and directory, presubmit.yml copied from the module;
- `.bcr/config.yml`: the module roots publish-to-bcr knows;
- the module table of `addons/README.md`, between its two markers;
- `addons/consumers.pkl`: the modules of the checkout that use each add-on module, from their
  `local_path_override`s, which hk.pkl reads to select their tasks.

`python3 -m tools.addons.generated` (`mise run addons:generate`) writes them;
`--check` (`mise run test:setup`) fails when one is stale.
"""

import argparse
import json
import sys
from pathlib import Path

from tools.addons.modules import ROOT, AddonModule, all_modules, consumers

BEGIN = "<!-- Generated by `mise run addons:generate`: the add-on modules. -->"
END = "<!-- End of the generated add-on modules. -->"
REPOSITORY = "https://github.com/{OWNER}/{REPO}/releases/download/{TAG}"
CONFIG_HEADER = """\
# Generated by `mise run addons:generate` (tools/addons/generated.py) from the add-on modules.
# The modules of this repository that publish-to-bcr knows. Each release publishes only its
# tag's module (publish.yaml sets module_roots); a module below the root has its templates in
# .bcr/<root>/.
"""


CONSUMERS_HEADER = """\
// Generated by `mise run addons:generate` (tools/addons/generated.py) from the MODULE.bazel
// files: the modules of this checkout that use an add-on module through local_path_override,
// by the add-on module's directory. hk.pkl selects their tasks for changes to it.
"""


def as_json(value: object) -> str:
    return json.dumps(value, indent=2) + "\n"


def bcr_templates(module: AddonModule, root: Path) -> dict[str, str]:
    """A module's templates in .bcr/<root>/, by path relative to the repository."""
    metadata = json.loads((root / ".bcr/metadata.template.json").read_text())
    metadata["homepage"] = f"{metadata['homepage']}/tree/main/{module.path.as_posix()}"
    source = {
        "integrity": "**leave this alone**",
        "strip_prefix": f"{module.name}-{{VERSION}}",
        "url": f"{REPOSITORY}/{module.name}-{{VERSION}}.tar.gz",
    }
    directory = f".bcr/{module.path.as_posix()}"
    return {
        f"{directory}/metadata.template.json": as_json(metadata),
        f"{directory}/source.template.json": as_json(source),
        f"{directory}/presubmit.yml": (root / module.path / "presubmit.yml").read_text(),
    }


def config(modules: tuple[AddonModule, ...]) -> str:
    roots = [".", *(module.path.as_posix() for module in modules)]
    return CONFIG_HEADER + "moduleRoots:\n" + "".join(f'  - "{root}"\n' for root in roots)


def consumers_pkl(users: dict[str, tuple[str, ...]]) -> str:
    entries = "".join(
        f"  [{json.dumps(name)}] = List({', '.join(map(json.dumps, modules))})\n"
        for name, modules in users.items()
    )
    return (
        CONSUMERS_HEADER
        + "consumers = new Mapping<String, List<String>> {\n"
        + entries
        + "}\n"
    )


def table(modules: tuple[AddonModule, ...]) -> str:
    if not modules:
        return "No add-on module yet: create one with `mise run addon:new <module>`.\n"
    rows = [
        f"| [`{module.name}`]({module.directory}) | {module.summary} | {module.version} |"
        for module in modules
    ]
    return (
        "\n".join(["| Module | Add-ons | Version |", "| --- | --- | --- |", *rows]) + "\n"
    )


def readme(text: str, modules: tuple[AddonModule, ...]) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"addons/README.md: the markers {BEGIN} and {END} are missing")
    return text[: start + len(BEGIN)] + "\n\n" + table(modules) + "\n" + text[end:]


def expected(root: Path = ROOT) -> dict[str, str | None]:
    """Every generated file's content by path; None for a stale file to remove."""
    modules = all_modules(root)
    files: dict[str, str | None] = {
        path.relative_to(root).as_posix(): None
        for path in (root / ".bcr/addons").rglob("*")
        if path.is_file()
    }
    for module in modules:
        files.update(bcr_templates(module, root))
    files[".bcr/config.yml"] = config(modules)
    files["addons/README.md"] = readme((root / "addons/README.md").read_text(), modules)
    files["addons/consumers.pkl"] = consumers_pkl(consumers(root))
    return files


def stale(root: Path = ROOT) -> list[str]:
    """The generated files whose content differs from what the modules say."""
    paths = []
    for path, content in expected(root).items():
        current = (root / path).read_text() if (root / path).is_file() else None
        if current != content:
            paths.append(path)
    return sorted(paths)


def write_file(target: Path, content: str | None) -> None:
    """Write one generated file, or remove it and its directory once that is empty."""
    if content is not None:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
        return
    target.unlink()
    if not any(target.parent.iterdir()):
        target.parent.rmdir()


def write(root: Path = ROOT) -> None:
    for path, content in expected(root).items():
        write_file(root / path, content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when a file is stale")
    args = parser.parse_args()
    if not args.check:
        write()
    elif paths := stale():
        sys.exit(
            "Stale files of the add-on modules; run `mise run addons:generate`:\n  "
            + "\n  ".join(paths)
        )


if __name__ == "__main__":
    main()
