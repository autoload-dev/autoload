"""
Generate an opt-in Godot resources macro, leaving manual BUILD files intact.

This is deliberately a bounded generator, not a Gazelle extension. It owns only
its marked .bzl file. Project composition, dependencies, generated file labels,
runtime references, import boundaries and export choices stay in manual BUILD.
"""

import argparse
import json
import os
import sys
from collections.abc import Sequence
from fnmatch import fnmatchcase
from pathlib import Path

from tools.godot_files import DIRECTORY_MARKERS, is_sidecar_named, sidecar_source
from tools.resource_graph import ANALYZED_FORMATS, LEAF_FORMATS, OPAQUE_FORMATS

MARKER = "# Generated by rules_godot godot_build_files; DO NOT EDIT.\n"
# Videos and glTF buffers are rarely members; declare them explicitly.
SUFFIXES = (ANALYZED_FORMATS | LEAF_FORMATS | OPAQUE_FORMATS) - {".ogv", ".bin"}


def discover(
    root: Path, *, includes: Sequence[str] = (), excludes: Sequence[str] = ()
) -> list[str]:
    """
    Scan one Bazel package; never cross nested packages or follow symlinks.

    A sidecar is collected with its collected file and never on its own.
    """
    if not root.is_dir():
        raise ValueError("package root is not a directory: " + str(root))
    result, sidecars = [], []
    for directory, directories, files in os.walk(root, followlinks=False):
        current = Path(directory)
        relative_dir = current.relative_to(root)
        if relative_dir != Path(".") and any(
            (current / name).is_file() for name in ("BUILD", "BUILD.bazel")
        ):
            directories[:] = []
            continue
        # Godot never scans a directory holding a marker (tools/godot_files.py). The
        # package's own directory is the project's root when it holds a project.godot,
        # and Godot scans the root whatever it holds.
        project_root = current == root and "project.godot" in files
        if not project_root and any(name in files for name in DIRECTORY_MARKERS):
            directories[:] = []
            continue
        directories[:] = sorted(
            name
            for name in directories
            if not name.startswith((".", "bazel-")) and not (current / name).is_symlink()
        )
        for name in sorted(files):
            path = current / name
            relative = path.relative_to(root).as_posix()
            if path.is_symlink() or name.startswith(".") or name == "project.godot":
                continue
            if any(fnmatchcase(relative, pattern) for pattern in excludes):
                continue
            if is_sidecar_named(relative):
                sidecars.append(relative)
            elif (
                any(fnmatchcase(relative, pattern) for pattern in includes)
                if includes
                else path.suffix.lower() in SUFFIXES
            ):
                result.append(relative)
    collected = set(result)
    return sorted(
        result + [path for path in sidecars if sidecar_source(path) in collected]
    )


def render(paths: list[str]) -> str:
    lines = [
        MARKER.rstrip(),
        '"""Explicit sources from one package; import and runtime policy stay in BUILD."""',
        "",
        'load("@autoload_rules_godot//godot:defs.bzl", "godot_resources")',
        "",
        "def godot_package_resources(name, **kwargs):",
        '    """Declare these sources; forward explicit policy and generated resource paths."""',
        "    godot_resources(",
        "        name = name,",
        "        srcs = [",
    ]
    lines.extend(
        "            " + json.dumps(path, ensure_ascii=False) + ","
        for path in sorted(set(paths))
    )
    lines.extend(["        ],", "        **kwargs", "    )", ""])
    return "\n".join(lines)


def update(
    root: Path,
    output: Path,
    *,
    check: bool = False,
    includes: Sequence[str] = (),
    excludes: Sequence[str] = (),
) -> bool:
    if output.suffix != ".bzl":
        raise ValueError("generator output must be a dedicated .bzl file")
    if output.is_symlink():
        raise ValueError("refusing to replace a symlink: " + str(output))
    previous = output.read_text(encoding="utf-8") if output.exists() else None
    if previous is not None and not previous.startswith(MARKER):
        raise ValueError("refusing to overwrite an unmarked file: " + str(output))
    paths = discover(root, includes=includes, excludes=excludes)
    # An explicit broad include pattern must not make the output enumerate
    # itself on the next run, changing an otherwise current manifest.
    try:
        generated = output.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        generated = None
    expected = render([path for path in paths if path != generated])
    if previous == expected:
        return True
    if not check:
        output.write_text(expected, encoding="utf-8")
    return False


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(os.environ.get("BUILD_WORKING_DIRECTORY", ".")),
        help="one Bazel package directory (default: caller's directory)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("godot_files.bzl"),
        help="dedicated generated .bzl, relative to root unless absolute",
    )
    parser.add_argument(
        "--check", action="store_true", help="report drift without writing"
    )
    parser.add_argument(
        "--include",
        action="append",
        default=[],
        help="opt-in fnmatch pattern, replaces the default format allowlist",
    )
    parser.add_argument("--exclude", action="append", default=[])
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve()
        output = args.output if args.output.is_absolute() else root / args.output
        current = update(
            root, output, check=args.check, includes=args.include, excludes=args.exclude
        )
        if args.check and not current:
            print("generated Godot sources are stale: " + str(output), file=sys.stderr)
            return 1
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
