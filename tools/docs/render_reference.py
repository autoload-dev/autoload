"""Assemble the reference for public consumer entrypoints."""

import argparse
import json
from pathlib import Path
from typing import Any

from tools.docs.api_docs import read_inventory
from tools.docs.coverage import ModuleInfo, parse_module
from tools.docs.surface import assign_surface, validate_rendered

MARKER = "<!-- Generated by tools/docs/render_reference.py; do not edit. -->\n\n"


def render_site(
    inventory: dict[str, Any],
    metadata: dict[str, ModuleInfo],
    rendered: dict[str, str],
    names: dict[str, str],
) -> dict[str, str]:
    assign_surface(inventory, metadata)
    pages = {}
    for label, entry in inventory["PUBLIC_APIS"].items():
        content = rendered[label]
        validate_rendered(content, entry["symbols"], label)
        path = f"reference/{names[label]}.md"
        pages[path] = MARKER + content

    lines = [
        MARKER.rstrip(),
        "",
        "# Bazel API reference",
        "",
        "Choose an entrypoint by task. Each public symbol has one reference and one public load path.",
        "",
    ]
    groups: dict[str, list[tuple[str, dict[str, Any]]]] = {}
    for label, entry in inventory["PUBLIC_APIS"].items():
        groups.setdefault(entry["group"], []).append((label, entry))
    for group, entries in groups.items():
        lines.extend(
            [
                f"## {group}",
                "",
                "| Primary load entrypoint | Purpose and symbols |",
                "| --- | --- |",
            ]
        )
        for label, entry in entries:
            path = f"reference/{names[label]}.md"
            links = ", ".join(
                f"[`{symbol}`]({path}#{symbol})" for symbol in entry["symbols"]
            )
            lines.append(
                f"| `@autoload_rules_godot{label}` | {entry['purpose']}<br>{links} |"
            )
        lines.append("")
    lines.extend(
        [
            "## Public target labels",
            "",
            "See [platform prerequisites](../platforms.md) for SDK and toolchain setup.",
            "",
            "| Label | Contract |",
            "| --- | --- |",
        ]
    )
    for label, description in sorted(inventory["PUBLIC_TARGETS"].items()):
        lines.append(f"| `@autoload_rules_godot{label}` | {description} |")
    pages["index.md"] = "\n".join(lines) + "\n"
    return pages


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    spec = json.loads(args.spec.read_text())
    inventory = read_inventory(Path(spec["manifest"]))
    metadata = {
        label: parse_module(Path(path).read_text())
        for label, path in spec["metadata"].items()
    }
    rendered = {label: Path(path).read_text() for label, path in spec["rendered"].items()}
    pages = render_site(inventory, metadata, rendered, spec["names"])
    args.output.mkdir(parents=True, exist_ok=True)
    for relative, content in pages.items():
        path = args.output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
