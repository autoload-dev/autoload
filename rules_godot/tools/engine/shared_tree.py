"""
Prepare a shared tree repository: the patched source tree of every recipe of one row.

Prototype. The repository rule has extracted and patched the source; this adds the
recipes' custom modules and build profiles, scopes the build profile like rendering does,
and writes the BUILD file that declares the recipes' shared work.
"""

import argparse
import hashlib
import shutil
from pathlib import Path

try:
    from . import build_profile
except ImportError:
    import build_profile


def add_custom_modules(root: Path, declarations: list[str]) -> None:
    """Copy each `name=directory` custom module below _custom_modules, as configuring does."""
    for declaration in declarations:
        name, _, directory = declaration.partition("=")
        shutil.copytree(
            directory,
            root / "_custom_modules" / name,
            ignore=shutil.ignore_patterns(".git", "__pycache__", "BUILD", "BUILD.bazel"),
            dirs_exist_ok=True,
        )


def add_profiles(root: Path, profiles: list[str]) -> None:
    """Copy each build profile to _build_profiles/<digest>.gdbuild."""
    for profile in profiles:
        data = Path(profile).read_bytes()
        destination = (
            root / "_build_profiles" / (hashlib.sha256(data).hexdigest() + ".gdbuild")
        )
        destination.parent.mkdir(exist_ok=True)
        destination.write_bytes(data)


def build_file(macros: str, recipes: list[str]) -> str:
    """The BUILD file that declares the union of the recipes' shared work."""
    loads = [
        f'load("@{recipe}//:shared.bzl", recipe_{index} = "SHARED")'
        for index, recipe in enumerate(recipes)
    ]
    names = ", ".join(f"recipe_{index}" for index in range(len(recipes)))
    return "\n".join(
        [
            "# Generated by rules_godot; do not edit.",
            f'load("{macros}", "godot_shared_objects")',
            *loads,
            'package(default_visibility = ["//visibility:public"])',
            f'godot_shared_objects(name = "_root", recipes = [{names}])',
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--macros", required=True)
    parser.add_argument("--custom-module", action="append", default=[])
    parser.add_argument("--profile", action="append", default=[])
    parser.add_argument("--recipe", action="append", default=[])
    args = parser.parse_args()
    add_custom_modules(args.root, args.custom_module)
    add_profiles(args.root, args.profile)
    build_profile.scope(args.root)
    (args.root / "BUILD.bazel").write_text(build_file(args.macros, args.recipe))


if __name__ == "__main__":
    main()
